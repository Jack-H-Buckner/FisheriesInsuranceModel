### Calculates the natural capital asset price of a fishery: the
### expected net present value of future income from harvest given the
### current state of the population,
###
###     V(s) = E[ Σ_t δ^t income_t | s_0 = s ],  s = (log bt, Δlog bt, Mt_1)
###
### The population follows the dynamics in population_model.jl under the
### harvest control rule, and income is given by income_model.jl. There are
### no insurance, savings or consumption decisions so this is a policy
### evaluation problem (one dummy action) solved with value function iteration.
###
### Usage (e.g. from a notebook run at the repo root):
###     include("src/natural_capital.jl")           # loads model.jl functions first
###     include("parameters/RA_intermidiate.jl")   # defines the global p
###     V, prob, Xmc = solve_natural_capital(p)
###     V([log(0.4), 0.0, 1.0])                     # price at the target stock
###
### NOTE: beverton_holt in population_model.jl reads the global `p`, so the
### parameter set used here must be bound to `p` in the calling scope (Main).
###
### This file was generated by Claude Code (Anthropic).
### Reviewed by Jack H. Buckner, Oregon State University, November 2026
#####################################################################
#####################################################################

include("model.jl")

# Grid bounds for log biomass and its change, chosen as in run_no_insurance.jl.
function natural_capital_grids(params_name = ""; Nb = 24, NΔb = 18)
    bmax = 0.5; bmin = -3.5
    Δbmax = 1.25; Δbmin = -1.0
    if occursin("short", params_name)
        bmax = 1.0; bmin = -3.0
        Δbmax = 2; Δbmin = -1.25
    elseif occursin("long", params_name)
        bmax = 0.0; bmin = -4.5
        Δbmax = 0.75; Δbmin = -0.75
    end
    b_grid = range(bmin, bmax, length = Nb)
    Δb_grid = range(Δbmin, Δbmax, length = NΔb)
    return b_grid, Δb_grid
end

# Per-period payoff. With utility_payoff = false this is income (a dollar value).
# With utility_payoff = true it is CRRA utility of income, using p.γ and the
# bankruptcy-level consumption p.κ_bankrupt (from income_model.jl). CRRA is undefined
# for income <= 0, so income is floored at p.κ_bankrupt, i.e. a period with
# non-positive income yields the same utility as bankruptcy. With p.γ = 0 utility
# is linear in income, so the (risk-neutral) price is income NPV, floored at κ_bankrupt.
function period_payoff(y, p, utility_payoff)
    utility_payoff || return y
    return utility(max(y, p.κ_bankrupt), 0.0, p.κ_bankrupt, p.γ)
end

# Build the (unsolved) dynamic program for the natural capital price.
# State is s = [log bt, Δlog bt, Mt_1] with Mt_1 ∈ {1,2}.
function init_natural_capital(p; δ = 0.95, b_grid = nothing, Δb_grid = nothing,
                              params_name = "", Nquad = 50, utility_payoff = false,
                              payoff = nothing)
    # payoff: optional function y -> per-period reward (e.g. shortfall_payoff(τ)).
    # It takes precedence over utility_payoff.
    reward = payoff === nothing ? (y -> period_payoff(y, p, utility_payoff)) : payoff
    if b_grid === nothing || Δb_grid === nothing
        b_grid, Δb_grid = natural_capital_grids(params_name)
    end

    # Random variables. Rows: basis risk, price, cost of effort, recruitment
    # deviation, mortality draw. Same construction as init_ranom_variables but
    # without the bankruptcy state that function expects.
    X1 = GaussHermiteRandomVariable(Nquad, [0.0], [p.σ_R^2;;])
    X2 = MarkovChain(p.T)
    X3 = RandomVariable([p.μZ; p.μ_P; p.μ_Ce;;], [1.0, 1.0, 1.0])
    X = product(product(X3, X1), X2)
    _, Xmc = init_ranom_variables(p; Nquad = Nquad) # for Monte Carlo checks

    u(s, p) = [1.0;;] # single dummy action

    F(s, u, X, p) = update_stock(s, X[4:5], p)[1]

    function R(s, u, X, p)
        _, ht, ft = update_stock(s, X[4:5], p)
        return reward(income(ht, ft, X[2], X[3]))
    end

    V = ValueFunction(b_grid, Δb_grid, 1.0:2.0)
    prob = DynamicProgram(V, R, F, p, u, X, δ; solve = false)
    return prob, Xmc
end

# Solve for the natural capital asset price. Returns
#   value_fn: callable, value_fn([log b, Δlog b, M]) -> asset price
#   prob:     the solved DynamicProgram (e.g. for save_solution)
#   Xmc:      Monte Carlo random variable for simulate_npv checks
function solve_natural_capital(p; δ = 0.95, b_grid = nothing, Δb_grid = nothing,
                               params_name = "", Nquad = 50, utility_payoff = false,
                               payoff = nothing,
                               maxiter = round(Int, 5/(1-δ)), tolerance = 1e-5)
    prob, Xmc = init_natural_capital(p; δ = δ, b_grid = b_grid, Δb_grid = Δb_grid,
                                     params_name = params_name, Nquad = Nquad,
                                     utility_payoff = utility_payoff, payoff = payoff)
    solve!(prob, maxiter = maxiter, tolerance = tolerance)
    return (s -> prob.V(s)), prob, Xmc
end

# Convenience wrapper taking a state vector s = [b, Δb, M] with biomass b (not log),
# the lagged change in log biomass Δb, and the mortality state M ∈ {1,2}.
# A 3 × N matrix (one state per column) returns a vector of N prices.
natural_capital_price(value_fn, s::AbstractVector) = value_fn([s[1], s[2], float(s[3])])
natural_capital_price(value_fn, s::AbstractMatrix) = [natural_capital_price(value_fn, s[:, i]) for i in 1:size(s, 2)]

# Monte Carlo estimate of the NPV from state s0 as a check on the value function.
# Pass utility_payoff = true to discount utility of income (matches solve_natural_capital).
# Pass payoff = y -> reward (e.g. shortfall_payoff(τ)) to discount a custom payoff instead.
function simulate_npv(p, Xmc, s0, T::Int, δ; utility_payoff = false, payoff = nothing)
    reward = payoff === nothing ? (y -> period_payoff(y, p, utility_payoff)) : payoff
    s = float.(s0); npv = 0.0
    for t in 0:(T-1)
        Xmc()
        ind = sample(1:length(Xmc.weights), Weights(Xmc.weights))
        Xt = Xmc.nodes[:, ind]
        s, ht, ft = update_stock(s, Xt[4:5], p)
        # income uses the choice made at the start of the period, as in R() above
        npv += δ^t * reward(income(ht, ft, p.μ_P, p.μ_Ce))
    end
    return npv
end

# Convert a value computed with utility_payoff = true into a certainty equivalent:
# the constant annual income that gives the same discounted utility,
# the κ solving utility(κ) = (1-δ)·V. Comparable to the dollar-valued price.
# Note: income_model.jl's inverse_utility omits the "+1" that utility() adds, so it does
# not invert utility() exactly; the "- 1" below corrects for that.
certainty_equivalent_income(V, δ, p) = inverse_utility((1 - δ) * V - 1, p.γ)/(1 - δ)

#####################################################################
### Expected present value of income shortfall below a threshold τ,
###     S_τ(s) = E[ Σ_t δ^t max(0, τ - y_t) | s_0 = s ],
### where y_t is net income (as in the natural capital price) and δ is the
### discount factor (weight δ^t, as elsewhere in this file). Thresholds are
### absolute income levels (target income is 1.0). Each threshold needs its
### own solve since the value function is scalar valued.
#####################################################################

# Per-period shortfall of income y below threshold τ.
shortfall_payoff(τ) = y -> max(0.0, τ - y)

# Solve for the expected PV of shortfall for each threshold in `thresholds`.
# Returns (shortfalls, Xmc) where `shortfalls` is a Dict mapping each threshold τ to a
# callable S_τ(s), s = [log b, Δlog b, M] (same state convention as the price function):
#     shortfalls, Xmc = solve_shortfalls(p, [0.5, 0.75, 1.0])
#     shortfalls[0.75]([log(0.4), 0.0, 1.0])
# The same grids are used for every threshold so results are comparable. Solves run in
# parallel if Julia was started with several threads (julia -t N).
function solve_shortfalls(p, thresholds; δ = 0.95, b_grid = nothing, Δb_grid = nothing,
                          params_name = "", Nquad = 50,
                          maxiter = round(Int, 5/(1-δ)), tolerance = 1e-5)
    if b_grid === nothing || Δb_grid === nothing
        b_grid, Δb_grid = natural_capital_grids(params_name)
    end
    τs = collect(float.(thresholds))
    fns = Vector{Any}(undef, length(τs)); Xmcs = Vector{Any}(undef, length(τs))
    Threads.@threads for i in eachindex(τs)
        fns[i], _, Xmcs[i] = solve_natural_capital(p; δ = δ, b_grid = b_grid, Δb_grid = Δb_grid,
                                                   Nquad = Nquad, maxiter = maxiter,
                                                   tolerance = tolerance,
                                                   payoff = shortfall_payoff(τs[i]))
    end
    return Dict{Float64,Any}(τs[i] => fns[i] for i in eachindex(τs)), Xmcs[1]
end

# Evaluate every threshold's shortfall at a state s = [log b, Δlog b, M]. Returns the
# thresholds (sorted) and a vector of values. A 3 × N matrix (one state per column)
# returns a (thresholds × N) matrix.
function shortfall_values(shortfalls, s::AbstractVector)
    τs = sort(collect(keys(shortfalls)))
    return τs, [shortfalls[τ](float.(s)) for τ in τs]
end
function shortfall_values(shortfalls, s::AbstractMatrix)
    τs = sort(collect(keys(shortfalls)))
    return τs, [shortfalls[τ](float.(s[:, j])) for τ in τs, j in axes(s, 2)]
end
